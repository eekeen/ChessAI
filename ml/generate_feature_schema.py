"""Generate/check the C++ constants from the shared V2 JSON feature contract."""
import argparse
from pathlib import Path
from features_v2 import SCHEMA, SCHEMA_HASH, INPUT_SIZE


def header():
    kinds = {name: i for i, name in enumerate(["count", "balance", "phase", "pair", "king"])}
    lines = ["// Generated by ml/generate_feature_schema.py; edit feature_schema_v2.json.",
             "#pragma once", "namespace FeatureSchemaV2 {",
             f"inline constexpr int InputSize = {INPUT_SIZE};",
             f"inline constexpr int BaseSize = {SCHEMA['base_size']};",
             f'inline constexpr char Hash[] = "{SCHEMA_HASH}";',
             "inline constexpr int Material[] = {" + ",".join(map(str, SCHEMA["material_values"])) + "};",
             "inline constexpr int Phase[] = {" + ",".join(map(str, SCHEMA["phase_weights"])) + "};",
             "struct Scalar { int kind, plane; float scale; int threshold, square1, square2; };",
             "inline constexpr Scalar Scalars[] = {"]
    for spec in SCHEMA["scalars"]:
        squares = spec.get("squares", [0, 0])
        lines.append(f"    {{{kinds[spec['kind']]}, {spec.get('plane', 0)}, {spec.get('scale', 1)}.0f, "
                     f"{spec.get('threshold', 0)}, {squares[0]}, {squares[1]}}}, // {spec['name']}")
    return "\n".join(lines + ["};", "}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "src/engine/FeatureSchemaV2.h"
    if args.check:
        if target.read_text() != header():
            raise SystemExit("FeatureSchemaV2.h is stale; regenerate it")
        print("Shared feature schema matches generated C++ header")
    else:
        target.write_text(header(), encoding="utf-8")
