"""Export V2 direct or residual checkpoints without touching the V1 header."""
import argparse
import hashlib
from pathlib import Path
from model_v2 import load_checkpoint
from features_v2 import INPUT_SIZE, SCHEMA_HASH


def export(checkpoint, output_dir):
    model, metadata = load_checkpoint(checkpoint)
    if metadata.get("synthetic"):
        raise ValueError("Do not deploy synthetic V2 models")
    name = "DirectWeightsV2" if metadata["kind"] == "direct" else "ResidualWeightsV2"
    digest = hashlib.sha256(Path(checkpoint).read_bytes()).hexdigest()
    lines = ["// Generated by ml/export_v2.py. Dropout is disabled for inference.", "#pragma once",
             "#include <string_view>", '#include "FeatureSchemaV2.h"', f"struct {name} {{",
             f"inline static constexpr int InputSize = {INPUT_SIZE};",
             "inline static constexpr int Hidden1 = 128, Hidden2 = 64;",
             "inline static constexpr float TargetScale = 1000.0f;",
             f'inline static constexpr char ModelVersion[] = "v2-{metadata["kind"]}-{digest[:16]}";']
    for layer_index, layer_number in [(0, 1), (3, 2), (5, 3)]:
        layer = model.layers[layer_index]
        weight = layer.weight.detach().numpy()
        if layer_number == 1:
            weight = weight.T
        for prefix, array in [("W", weight), ("B", layer.bias.detach().numpy())]:
            flat = array.ravel()
            lines.append(f"inline static constexpr float {prefix}{layer_number}[{len(flat)}] = {{")
            lines.extend("    " + ", ".join(f"{value:.9e}f" for value in flat[i:i + 8]) + ","
                         for i in range(0, len(flat), 8))
            lines.append("};")
    lines.extend(["};", f'static_assert(std::string_view(FeatureSchemaV2::Hash) == "{SCHEMA_HASH}", "V2 feature schema mismatch");'])
    directory = Path(output_dir)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / (name + ".h")
    temporary = path.with_suffix(".tmp")
    temporary.write_text("\n".join(lines) + "\n", encoding="utf-8")
    temporary.replace(path)
    print(f"Exported {path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkpoint", required=True)
    parser.add_argument("--output-dir", default="src/engine/generated")
    args = parser.parse_args()
    export(args.checkpoint, args.output_dir)
