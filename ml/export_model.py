"""Export a validated checkpoint as C++17 float arrays (no runtime ML library)."""
import argparse
import hashlib
from pathlib import Path
import numpy as np
from model import load_checkpoint


def export(checkpoint_path, output, allow_synthetic=False):
    model, checkpoint = load_checkpoint(checkpoint_path)
    if checkpoint.get("synthetic") and not allow_synthetic:
        raise ValueError("Synthetic checkpoint: use --allow-synthetic only in an isolated test build")
    digest = hashlib.sha256(Path(checkpoint_path).read_bytes()).hexdigest()
    text = ["// Generated by ml/export_model.py. Do not edit.", "#pragma once", "namespace MLWeights {",
            "inline constexpr int FeatureVersion = 1;", "inline constexpr int InputSize = 773;",
            "inline constexpr int Hidden1 = 128;", "inline constexpr int Hidden2 = 64;",
            "inline constexpr float TargetScale = 1000.0f;", "inline constexpr float ClipCp = 1500.0f;",
            f'inline constexpr char ModelVersion[] = "{checkpoint["model_version"]}-{digest[:16]}";',
            f'inline constexpr bool Synthetic = {str(bool(checkpoint.get("synthetic"))).lower()};']
    # Layer 1 input-major: sparse input additions traverse contiguous hidden weights.
    arrays = {"W1": model.layers[0].weight.detach().numpy().T,
              "B1": model.layers[0].bias.detach().numpy(),
              "W2": model.layers[2].weight.detach().numpy(),
              "B2": model.layers[2].bias.detach().numpy(),
              "W3": model.layers[4].weight.detach().numpy(),
              "B3": model.layers[4].bias.detach().numpy()}
    for name, array in arrays.items():
        flat = array.astype(np.float32).ravel()
        text.append(f"inline constexpr float {name}[{flat.size}] = {{")
        for start in range(0, len(flat), 8):
            text.append("    " + ", ".join(f"{v:.9e}f" for v in flat[start:start + 8]) + ",")
        text.append("};")
    text.append("} // namespace MLWeights")
    path = Path(output)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(text) + "\n", encoding="utf-8")
    print(f"Exported {path}; checkpoint SHA256 {digest}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkpoint", default="ml/models/best.pt")
    parser.add_argument("--output", default="src/engine/generated/MLWeights.h")
    parser.add_argument("--allow-synthetic", action="store_true")
    args = parser.parse_args()
    export(args.checkpoint, args.output, args.allow_synthetic)
